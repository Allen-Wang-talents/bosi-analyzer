// 长度异常的兜底
//   - 纯英文公司名（如 ByteDance / Alibaba）至少需要 3 个英文字母
//   - 含中文公司名至少需要 2 个中文字
function isTooShortAsCompany(name: string): boolean {
  const cnCount = (name.match(/[一-龥]/g) || []).length;
  if (cnCount === 0) {
    return name.replace(/[^a-zA-Z]/g, '').length < 3;
  }
  return cnCount < 2;
}

// Allen 2026-08-21 增补:
//   真实公司名通常较短(< 30 字符), 不应包含数字 / 多个标点 / 简历元信息词.
//   长尾字符串 (e.g. "2022.07-至今字节跳动抖音商城改版项目后端负责人")
//   即使没命中黑名单也极不可能是公司名, 直接 reject 防止漏到 scoreCompany 后被算成 Tier 4.
function looksObviouslyNotCompany(name: string): boolean {
  // 含 4 位以上连续数字 (年份 / 项目编号)
  if (/\d{4}/.test(name)) return true;
  // 含 3+ 个标点
  const punctCount = (name.match(/[·•\-—–\/\\|｜,，。、:：;；()()【】\[\]/\\]/g) || []).length;
  if (punctCount >= 3) return true;
  // 总长度 > 30 (Allen 限制 company.slice(0, 30), 超过必丢)
  if (name.length > 30) return true;
  // 含明显是叙述的助词 (避免 "字节跳动的抖音电商后端" 漏过)
  if (/(?:的|了|是|在|和|与|或)$/.test(name)) return true;
  // 含英文标点空格紧邻 (如 "ABC, Inc." / "X.Y.Z" 这种多个点)
  if (/[A-Za-z]\.[A-Za-z]/.test(name)) return true;
  return false;
}

// 判断是否为产品/项目名（非公司名）
export function isProductName(name: string): boolean {
  if (!name) return false;
  // 命中反向映射 → 是产品名（但可解析）
  if (PRODUCT_TO_COMPANY_MAP[name]) return true;
  // 含产品/系统词 → 是产品名
  for (const kw of PRODUCT_NOISE_KEYWORDS) {
    if (name.includes(kw)) return true;
  }
  // 全英文产品/工具词尾
  if (/^[A-Z][a-zA-Z]+(Studio|Cloud|Hub|Console|Workspace|Engine|Suite|Platform|Service)$/.test(name)) return true;
  // 长度过短
  if (isTooShortAsCompany(name)) return true;
  // Allen 2026-08-21: 长尾字符串 / 含年份 / 多标点 - 显然不是公司名
  if (looksObviouslyNotCompany(name)) return true;
  return false;
}

// 公司名解析：把候选名解析为真正的公司名
// 返回: 字符串 (替换或原值) / null (识别不出，应跳过候选)
//
// Allen 2026-08-12 增强:
//   1) 先按 `|` `-` `—` `,` `，` 切分候选名，对每个 segment 独立解析
//      例: "字节跳动 - 抖音电商" → "字节跳动"
//      例: "字节跳动|抖音电商后端" → "字节跳动"
//   2) 多个 segment 都能解析时, 优先取长度最长(更具体)的母公司
//   3) 单 segment 解析失败时, 整体走原路径
//
// Allen 2026-08-21 增强:
//   4) 兜底原样返回前, 走 looksObviouslyNotCompany 严格过滤, 避免长尾字符串
//      (年份/多标点/简历元信息) 漏到 scoreCompany 算成 Tier 4.
export function resolveCompanyName(name: string): string | null {
  const cleaned = name.trim();
  if (!cleaned) return null;

  // 0) 显然不是公司名 (含年份 / 多标点 / 超长) → 直接 reject
  if (looksObviouslyNotCompany(cleaned)) return null;

  // 1) 精确匹配反向映射（先快路径）
  if (PRODUCT_TO_COMPANY_MAP[cleaned]) {
    return PRODUCT_TO_COMPANY_MAP[cleaned];
  }

  // 2) 包含产品名 → 优先匹配长产品名（处理 "字节跳动 - 抖音电商"）
  const sortedProducts = Object.keys(PRODUCT_TO_COMPANY_MAP).sort((a, b) => b.length - a.length);
  for (const product of sortedProducts) {
    if (cleaned.includes(product)) {
      return PRODUCT_TO_COMPANY_MAP[product];
    }
  }

  // 3) 多分隔符场景: 按 `|` `-` `—` 切, 选最长的母公司
  const segments = cleaned.split(/[|｜\-—–\/、]/).map(s => s.trim()).filter(Boolean);
  if (segments.length > 1) {
    let bestParent: string | null = null;
    let bestLen = 0;
    for (const seg of segments) {
      // 递归 (但跳过 multi-segment 切分, 避免无限嵌套)
      const parent = resolveCompanyNameSingle(seg);
      if (parent && parent.length > bestLen) {
        bestParent = parent;
        bestLen = parent.length;
      }
    }
    if (bestParent) return bestParent;
  }

  // 4) 命中纯产品词（无映射）→ 视为非公司名
  if (isProductName(cleaned)) {
    return null;
  }

  // 5) 看起来像正常公司名 → 原样返回
  return cleaned;
}

// 单 segment 解析（避免多切分递归）
function resolveCompanyNameSingle(name: string): string | null {
  const cleaned = name.trim();
  if (!cleaned) return null;

  if (looksObviouslyNotCompany(cleaned)) return null;

  if (PRODUCT_TO_COMPANY_MAP[cleaned]) {
    return PRODUCT_TO_COMPANY_MAP[cleaned];
  }

  const sortedProducts = Object.keys(PRODUCT_TO_COMPANY_MAP).sort((a, b) => b.length - a.length);
  for (const product of sortedProducts) {
    if (cleaned.includes(product)) {
      return PRODUCT_TO_COMPANY_MAP[product];
    }
  }

  if (isProductName(cleaned)) {
    return null;
  }

  return cleaned;
}

