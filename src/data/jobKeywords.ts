/** 取某方向的全部词组 (含通用词) */
export function keywordGroupsFor(track: JobTrack): KeywordGroup[] {
  return [...COMMON_KEYWORDS, ...(TRACK_KEYWORDS[track] ?? [])];
}

/**
 * 只取该方向自己的词组 (不含通用 AI 词)。
 * 判断「候选人是这个方向的人」时必须用它 —— 通用词 (评测/训练/Agent) 每个方向都有,
 * 混进去会让所有方向的亲和度一起抬高, 方向就区分不出来了。
 */
export function trackKeywordsFor(track: JobTrack): KeywordGroup[] {
  return TRACK_KEYWORDS[track] ?? [];
}
